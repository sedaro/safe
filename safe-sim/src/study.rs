//! Shared execution and result types for named trade studies and Monte Carlo studies.
//!
//! Studies execute sequentially because EDS target files currently share a workspace. A caller
//! must give each concurrently running study a separate EDS workspace.

use std::collections::{BTreeMap, HashSet};
use std::time::{Duration, Instant};

use anyhow::{Result, bail};
use rand::{Rng, RngCore, SeedableRng};
use rand_chacha::ChaCha8Rng;
use rand_distr::{Distribution, LogNormal, Normal, Triangular, Uniform};
